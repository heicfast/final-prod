#!/usr/bin/env python3
"""gen_abi_layouts.py — the ABI layout gate's single source of truth.

Parses engine/include/cr/cr_ui.h's struct definitions and emits, from the
SAME parse, the two halves of the bridge ABI layout gate (BF-ABI-01
closure — the class of drift where eb4bb5f3 appended bus_type /
power_cycles_nvme to the C structs and the Rust bridge was never
re-pinned, producing an 8xN-byte heap overflow in enumerate_disks and a
16-byte stack smash on every health read):

  1) engine/tests/abi_layout_dump.c
     Plain-C dumper (same stance as ui_abi_check.c: proves the header
     compiles standalone under a plain C compiler) that prints a JSON
     manifest: {"<cr_ui_x>": {"size": N, "fields": {"<name>": <offset>,
     ...}}, ...} — the MSVC-side layout TRUTH, computed by offsetof at
     build time. The bridge-integration lane runs it against the BUILT
     engine.

  2) ui/src-tauri/it/tests/abi_layouts.rs
     The Rust mirror side: a generated `rust_layouts()` returning the
     same shape, with offsets computed by memoffset::offset_of! on the
     actual #[repr(C)] structs in the bridge, plus the comparison test
     (struct set, size, every field offset) against the engine manifest.

When the header gains a field: re-run this script, re-pin
ui/src-tauri/src/bridge/abi.rs to match, and both sides go green
together.

Nested struct fields are expanded one level (cr_ui_telemetry's
quick/deep/carve carry cr_ui_stage_tel members) so inner drift is
pinned too.

Usage: python tools/gen_abi_layouts.py <repo_root>
"""

import hashlib
import re
import sys
from pathlib import Path

HEADER_STRUCT_RE = re.compile(
    r"typedef\s+struct\s+(cr_ui_\w+)\s*\{(.*?)\}\s*(cr_ui_\w+)\s*;", re.S
)

FIELD_RE = re.compile(
    r"^\s*((?:const\s+)?[\w]+\s*(?:\*\s*(?:const\s*)?)*)"  # base type (+ ptrs)
    r"([\w]+(?:\s*\[[^\]]*\])?"                            # first name (+array?)
    r"(?:\s*,\s*[\w]+(?:\s*\[[^\]]*\])?)*)\s*;"            # ", name" repeats
)

SCALARS = {"char": 1, "uint8_t": 1, "uint16_t": 2, "uint32_t": 4,
           "uint64_t": 8, "int": 4, "int64_t": 8, "size_t": 8, "bool": 1}

STRUCTS = {}


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def parse_structs(header: str):
    out = {}
    for m in HEADER_STRUCT_RE.finditer(strip_comments(header)):
        _tag, body, name = m.group(1), m.group(2), m.group(3)
        assert _tag == name, f"tag/name mismatch: {_tag} vs {name}"
        fields = []
        for line in body.splitlines():
            line = line.strip()
            if not line:
                continue
            fm = FIELD_RE.match(line)
            if not fm:
                raise ValueError(f"unparsed field line in {name}: {line!r}")
            base = fm.group(1).strip()
            is_array = "[" in fm.group(2)
            names = [n.strip().split("[")[0] for n in fm.group(2).split(",") if n.strip()]
            for n in names:
                fields.append({
                    "name": n,
                    "type": base,
                    "is_array": is_array,
                    "is_ptr": "*" in base,
                })
        out[name] = fields
    return out


def nested_type(f):
    """cr_ui_X struct value field (not pointer, not array) -> its name."""
    if f["is_ptr"] or f["is_array"]:
        return None
    t = f["type"].replace("const ", "").strip()
    return t if t.startswith("cr_ui_") and t in STRUCTS else None


def field_paths(struct_name):
    """[(path, kind)] — kind: 'scalar'|'ptr'|'array'|'nested'."""
    out = []
    for f in STRUCTS[struct_name]:
        nt = nested_type(f)
        if nt:
            for sub in STRUCTS[nt]:
                out.append((f"{f['name']}.{sub['name']}", "nested"))
        else:
            kind = "ptr" if f["is_ptr"] else ("array" if f["is_array"] else "scalar")
            out.append((f["name"], kind))
    return out


def gen_c_dumper() -> str:
    names = sorted(STRUCTS.keys())
    L = [
        "/*",
        " * abi_layout_dump.c — GENERATED by tools/gen_abi_layouts.py.",
        " * DO NOT EDIT BY HAND. Re-run the generator when cr_ui.h changes",
        " * (bridge-integration.yml fails a freshness checksum first if you",
        " * forget).",
        " *",
        " * Dumps the MSVC-side ABI layout truth as JSON: every struct's",
        " * size and every field's offsetof (nested one level for the",
        " * stage-tel members). Plain C, like ui_abi_check.c. The",
        " * bridge-integration lane feeds this manifest to the Rust layout",
        " * gate — the two-sided pin that closed BF-ABI-01.",
        " */",
        "",
        '#include "cr/cr_ui.h"',
        "",
        "#include <stdio.h>",
        "#include <stddef.h>",
        "",
        "int main(int argc, char** argv) {",
        "    FILE* out = stdout;",
        "    if (argc > 1) {",
        '        out = fopen(argv[1], "wb");',
        "        if (!out) return 2;",
        "    }",
        '    fputs("{\\n", out);',
    ]
    for si, name in enumerate(names):
        paths = field_paths(name)
        L.append(
            '    fprintf(out, "  \\"%s\\": {\\"size\\": %llu, \\"fields\\": {", '
            f'"{name}", (unsigned long long)sizeof({name}));'
        )
        for fi, (path, _kind) in enumerate(paths):
            comma = "," if fi < len(paths) - 1 else ""
            L.append(
                '    fprintf(out, "\\"%s\\": %llu%s ", '
                f'"{path}", (unsigned long long)offsetof({name}, {path}), "{comma}");'
            )
        L.append('    fputs("}}%s\\n", out);' % ("," if si < len(names) - 1 else "",))
    L += [
        '    fputs("}\\n", out);',
        "    if (out != stdout) fclose(out);",
        "    return 0;",
        "}",
        "",
    ]
    return "\n".join(L)


RUST_NAME_CACHE = {}


def rust_name(n):
    if n not in RUST_NAME_CACHE:
        assert n.startswith("cr_ui_"), n
        parts = [p for p in n[len("cr_ui_"):].split("_") if p]
        RUST_NAME_CACHE[n] = "CrUi" + "".join(p.capitalize() for p in parts)
    return RUST_NAME_CACHE[n]


# The comparison test, emitted verbatim (raw string: no escaping battles).
RUST_TEST_BLOCK = r'''
// -------------------------------------------------------------------
// THE GATE: the generated Rust table vs the engine's dump manifest.
// (in the same generated file so the two can never diverge)
// -------------------------------------------------------------------

#[test]
fn layouts_match_engine_manifest() {
    let path = std::env::var("CR_ABI_LAYOUTS").expect(
        "CR_ABI_LAYOUTS must point at the engine's abi_layout_dump.c manifest (the \
         bridge-integration workflow runs the built dumper and sets it)",
    );
    let raw = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("read {path:?}: {e}"));
    let engine: serde_json::Value =
        serde_json::from_str(&raw).unwrap_or_else(|e| panic!("parse manifest: {e}"));
    let engine = engine.as_object().expect("manifest root is an object");
    let rust = rust_layouts();

    let rust_names: std::collections::BTreeSet<&str> =
        rust.iter().map(|s| s.name).collect();
    let engine_names: std::collections::BTreeSet<&str> =
        engine.keys().map(|k| k.as_str()).collect();
    let missing_in_rust: Vec<&str> =
        engine_names.difference(&rust_names).copied().collect();
    let missing_in_engine: Vec<&str> =
        rust_names.difference(&engine_names).copied().collect();
    assert!(
        missing_in_rust.is_empty(),
        "engine structs the Rust bridge does not mirror: {missing_in_rust:?} - re-pin \
         ui/src-tauri/src/bridge/abi.rs (and re-run tools/gen_abi_layouts.py)",
    );
    assert!(
        missing_in_engine.is_empty(),
        "Rust mirrors with no engine struct: {missing_in_engine:?} - stale abi.rs or a \
         stale generated table (re-run tools/gen_abi_layouts.py)",
    );

    for s in &rust {
        let e = &engine[s.name];
        let esize = e["size"].as_u64().expect("size") as usize;
        assert_eq!(
            s.size, esize,
            "{}: Rust sizeof({}) = {} but the engine's sizeof = {} - the mirror \
             drifted (BF-ABI-01 class; re-pin abi.rs field-for-field)",
            s.name, s.name, s.size, esize
        );
        let efields = e["fields"].as_object().expect("fields");
        let rnames: std::collections::BTreeSet<&str> =
            s.fields.iter().map(|f| f.name).collect();
        let enames: std::collections::BTreeSet<&str> =
            efields.keys().map(|k| k.as_str()).collect();
        let lack: Vec<&str> = enames.difference(&rnames).copied().collect();
        let extra: Vec<&str> = rnames.difference(&enames).copied().collect();
        assert!(
            lack.is_empty(),
            "{}: engine field(s) {lack:?} missing from the Rust mirror - re-pin \
             ui/src-tauri/src/bridge/abi.rs (append the field(s), same position)",
            s.name
        );
        assert!(
            extra.is_empty(),
            "{}: Rust field(s) {extra:?} the engine struct does not carry - a stale \
             mirror or a stale generated table (re-run tools/gen_abi_layouts.py)",
            s.name
        );
        for f in &s.fields {
            let eoff = efields[f.name].as_u64().expect("offset") as usize;
            assert_eq!(
                f.offset, eoff,
                "{}::{}: Rust offset {} != engine offset {} - the layout drifted \
                 (re-pin abi.rs)",
                s.name, f.name, f.offset, eoff
            );
        }
    }
}
'''


def gen_rust_table() -> str:
    names = sorted(STRUCTS.keys())
    L = []
    L += [
        "//! abi_layouts.rs — GENERATED by tools/gen_abi_layouts.py.",
        "//! DO NOT EDIT BY HAND. Re-run the generator when cr_ui.h changes.",
        "//!",
        "//! The Rust half of the bridge ABI layout gate (BF-ABI-01",
        "//! closure): `rust_layouts()` reports every mirrored struct's size",
        "//! and every field's offset (memoffset on the actual #[repr(C)]",
        "//! mirrors in the bridge). The test below compares this against",
        "//! the ENGINE's abi_layout_dump.c manifest — drift on either side",
        "//! fails the gate.",
        "//!",
        "//! Feature-gated (`layout-gate`): the it/ crate's workflow always",
        "//! passes --features layout-gate; without the feature this file",
        "//! compiles empty (the runtime tests still run).",
        "",
        '#![cfg(feature = "layout-gate")]',
        "",
        "#![allow(dead_code)]",
        "",
        "use memoffset::offset_of;",
        "",
        "use recovery_wizard_ui_lib::bridge::abi::*;",
        "",
        "pub struct FieldOff {",
        "    pub name: &'static str,",
        "    pub offset: usize,",
        "}",
        "",
        "pub struct StructLayout {",
        "    pub name: &'static str,",
        "    pub size: usize,",
        "    pub fields: Vec<FieldOff>,",
        "}",
        "",
        "pub fn rust_layouts() -> Vec<StructLayout> {",
        "    vec![",
    ]
    for name in names:
        paths = field_paths(name)
        L.append(
            f'        StructLayout {{ name: "{name}", size: std::mem::size_of::<{rust_name(name)}>(), fields: vec!['
        )
        for path, _kind in paths:
            L.append(
                f'            FieldOff {{ name: "{path}", offset: offset_of!({rust_name(name)}, {path}) }},'
            )
        L.append("        ] },")
    L += [
        "    ]",
        "}",
        "",
        RUST_TEST_BLOCK,
        "",
    ]
    return "\n".join(L)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    root = Path(sys.argv[1])
    global STRUCTS
    header = (root / "engine" / "include" / "cr" / "cr_ui.h").read_text(
        encoding="utf-8", errors="replace"
    )
    STRUCTS = parse_structs(header)
    total_fields = sum(len(field_paths(n)) for n in STRUCTS)
    print(f"parsed {len(STRUCTS)} structs, {total_fields} field paths")

    c_path = root / "engine" / "tests" / "abi_layout_dump.c"
    rs_path = root / "ui" / "src-tauri" / "it" / "tests" / "abi_layouts.rs"
    c_path.write_text(gen_c_dumper(), encoding="utf-8")
    rs_path.parent.mkdir(parents=True, exist_ok=True)
    rs_path.write_text(gen_rust_table(), encoding="utf-8")

    print(f"wrote {c_path}")
    print(f"wrote {rs_path}")
    # Persist the comment-stripped header checksum so the CI freshness gate
    # can detect a header change that did NOT re-run the generator.
    chk = root / "engine" / "tests" / "abi_layout_dump.header.sha"
    chk.write_text(
        hashlib.sha256(strip_comments(header).encode()).hexdigest() + "\n",
        encoding="utf-8",
    )
    print(f"wrote {chk}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

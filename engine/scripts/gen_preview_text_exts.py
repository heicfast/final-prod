#!/usr/bin/env python3
"""gen_preview_text_exts.py - generate the TxtViewFiles text-preview
extension whitelist from the corpus config file (M-108, diff-to-fix).

Source of truth: the og's shipped config/FilterFolder.ini [Filter]
TxtViewFiles line (corpus artifact filtering-priority--config-layer.md §3
+ the first-hand DRWUI decompile: the consumer at DRWUI_decompiled.c
:535858/:535937 loads the ini once, extracts the candidate's extension
(FUN_140089050), and runs the case-insensitive delimited membership test
(FUN_140310aa0 - toupper-folded substring search; the ini-read default
when the key is absent is ".txt;"). The list is the og's entry order,
byte-exact: 97 semicolon-delimited dot-prefixed tokens (92 unique after
case folding - the shipped list carries duplicates, e.g. .CFG thrice).

The entries are short functional file extensions - facts from the
shipped configuration, the same posture as the Dict/raw_signs/
FilterFolder corpus-data conversions.

The pool is emitted as a NUMERIC char initializer - escape-proof by
construction (mirrors gen_filterfolder.py). Regenerate after corpus
updates:
    python3 scripts/gen_preview_text_exts.py <path-to-FilterFolder.ini>

Output: src/core/preview/cr_preview_text_exts_data.cpp

Licensed under the MIT license. See LICENSE.
"""

import sys
import os

HEADER = """/* cr_preview_text_exts_data.cpp - GENERATED by
 * scripts/gen_preview_text_exts.py from the corpus FilterFolder.ini
 * (the og's text-preview extension whitelist, [Filter] TxtViewFiles -
 * byte-exact list, the og's entry order preserved; the consumer decode:
 * DRWUI_decompiled.c:535858/:535937, the toupper-folded membership
 * search FUN_140310aa0, the ".txt;" ini-absent default).
 * Do not edit by hand; regenerate after corpus updates.
 *
 * Licensed under the MIT license. See LICENSE.
 */

#include "cr/preview/cr_preview.h"

namespace cr {
namespace preview {
namespace textexts {
namespace data {

"""

FOOTER = """} // namespace data
} // namespace textexts
} // namespace preview
} // namespace cr
"""


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    src = sys.argv[1]
    with open(src, "rb") as f:
        raw = f.read()
    text = raw.decode("utf-8", errors="strict")
    # locate the [Filter] TxtViewFiles line (single line, CRLF-safe)
    line = None
    for ln in text.splitlines():
        if ln.startswith("TxtViewFiles="):
            line = ln[len("TxtViewFiles="):]
            break
    if line is None:
        print("TxtViewFiles= not found in %s" % src)
        sys.exit(1)
    tokens = [t for t in line.split(";") if t]
    # byte-exact pool: the value verbatim, NUL-terminated
    pool = line.encode("utf-8") + b"\x00"
    count = len(tokens)
    unique = len(set(t.lower() for t in tokens))

    rows = []
    for i in range(0, len(pool), 16):
        rows.append("    " + " ".join("0x%02X," % b for b in pool[i:i + 16]))
    body = (
        "/* %d tokens (%d unique case-folded), %d bytes: the og's "
        "TxtViewFiles\n"
        " * value verbatim (semicolon-delimited, trailing, "
        "NUL-terminated) */\n"
        "const u8 kTxtViewPool[] = {\n%s\n};\n"
        "const u32 kTxtViewPoolLen = sizeof(kTxtViewPool);\n"
        "constexpr u32 kTxtViewTokenCount = %d;\n"
    ) % (count, unique, len(pool), "\n".join(rows), count)

    out = os.path.join(os.path.dirname(__file__), "..", "src", "core",
                       "preview", "cr_preview_text_exts_data.cpp")
    with open(out, "w") as f:
        f.write(HEADER + body + FOOTER)
    print("wrote %s: %d tokens (%d unique), %d bytes"
          % (os.path.normpath(out), count, unique, len(pool)))


if __name__ == "__main__":
    main()

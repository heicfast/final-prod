#!/usr/bin/env python3
"""gen_filterfolder.py - generate the FilterFolder.ini hidden-name tables
from the corpus config file (M-018, diff-to-fix).

Source of truth: the og's shipped config/FilterFolder.ini (corpus
re-workspace artifact filtering-priority--config-layer.md §3; the file is
UTF-8 with CRLF lines; every list is semicolon-delimited with a LEADING
semicolon and an EMPTY tail after the trailing one). Three lists:

  [Filter]
  FolderName   - hidden folder names (Windows upgrade/setup scaffolding)
  FileName     - hidden file names (filesystem metadata noise)
  FatFilterName- the localized "New Folder" family + System Volume
                 Information + BitLocker recovery-password artifacts
                 (applies to any node kind - the list mixes files and
                 folders)

The entries are short functional identifiers (OS artifact filenames and
localized "New Folder" strings) - facts from the shipped configuration,
the same posture as the Dict/raw_signs corpus-data conversions.

The pools are emitted as NUMERIC char initializers - escape-proof by
construction (mirrors gen_dict.py; a CJK byte can never reparse as an
escape). Regenerate after corpus updates:
    python3 scripts/gen_filterfolder.py <path-to-FilterFolder.ini>

Output: src/core/orchestration/cr_filterfolder_data.cpp

Licensed under the MIT license. See LICENSE.
"""

import sys
import os

HEADER = """/* cr_filterfolder_data.cpp - GENERATED by scripts/gen_filterfolder.py
 * from the corpus FilterFolder.ini (the og's result-set junk filter,
 * config/FilterFolder.ini via filtering-priority--config-layer.md §3 -
 * byte-exact lists, the og's entry order preserved).
 * Do not edit by hand; regenerate after corpus updates.
 *
 * Licensed under the MIT license. See LICENSE.
 */

#include "cr/orchestrator/cr_filterfolder.h"

namespace cr {
namespace filterfolder {
namespace data {

"""


def parse_lists(path):
    lists = {}
    cur = None
    with open(path, "rb") as f:
        text = f.read().decode("utf-8")
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[") and line.endswith("]"):
            continue
        if "=" in line:
            key, _, val = line.partition("=")
            lists[key.strip()] = val.strip()
    return lists


def split_semi(val):
    # the og's lists: ";a;b;c;" - leading semicolon, trailing semicolon
    parts = [p for p in val.split(";") if p != ""]
    return parts


def emit_pool(name, entries, out):
    joined = ";".join(entries) + ";"
    raw = joined.encode("utf-8")
    out.append(f"/* {len(entries)} entries, {len(raw)} bytes (semicolon-delimited, trailing) */\n")
    out.append(f"const u8 k{name}Pool[] = {{\n")
    for i in range(0, len(raw), 16):
        chunk = raw[i:i + 16]
        out.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n")
    out.append("};\n")
    out.append(f"constexpr u32 k{name}Count = {len(entries)};\n\n")


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    src = sys.argv[1]
    lists = parse_lists(src)
    folders = split_semi(lists.get("FolderName", ""))
    files = split_semi(lists.get("FileName", ""))
    fat = split_semi(lists.get("FatFilterName", ""))
    if not folders or not files or not fat:
        print("ERROR: expected FolderName/FileName/FatFilterName in", src,
              file=sys.stderr)
        sys.exit(1)

    out = [HEADER]
    emit_pool("Folder", folders, out)
    emit_pool("File", files, out)
    emit_pool("FatName", fat, out)
    out.append("} // namespace data\n} // namespace filterfolder\n} // namespace cr\n")

    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                       "src", "core", "orchestrator", "cr_filterfolder_data.cpp")
    with open(dst, "w") as f:
        f.write("".join(out))
    print(f"generated {dst}: {len(folders)} folder + {len(files)} file + "
          f"{len(fat)} fat-name entries")


if __name__ == "__main__":
    main()

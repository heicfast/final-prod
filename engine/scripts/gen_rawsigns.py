#!/usr/bin/env python3
"""gen_rawsigns.py - generate the compiled raw-signature table from the
corpus raw_signs.json (the og's layer-1 carving database, 139 formats).

The corpus format per extension:
    { "header": {"signs": ["<offset>,<hex>,<confidence>", ...]},
      "tail":   {"signs": [...]},           # optional
      "min": <min KiB>, "max": <max KiB> }

The min/max fields are KiB COUNTS in the og (S-015, decoded from
RAWSearchDLL FUN_1800205b0: gate `span < max * 0x400`, emitted size
`max << 10`, tail-acceptance `size < (min << 10) -> reject`, default max
0x7d000 KiB = 500 MiB when absent/zero). This generator is the ONE
conversion point: it emits BYTES (KiB * 1024) into the compiled table.

Output: src/core/carve/cr_rawsigns_data.cpp - three sorted arrays plus the
extension string pool. Regenerate after corpus updates:
    python3 scripts/gen_rawsigns.py <path-to-raw_signs.json>

Licensed under the MIT license. See LICENSE.
"""

import json
import sys

MAX_SIGN = 40  # longest sign pattern we keep (corpus max observed: 32)


def parse_sign(s):
    off, hexs, conf = s.split(",")
    b = bytes.fromhex(hexs)
    assert len(b) <= MAX_SIGN, f"sign too long: {len(b)}"
    return int(off), b, int(round(float(conf) * 1000))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "../easeus-drw-research/og-codebase/raw_signs.json"
    db = json.load(open(src))
    exts = []
    hdr = []  # (offset, bytes, conf, fmt)
    tail = []
    fmts = []  # (ext, min, max)

    for ext in sorted(db.keys()):
        e = db[ext]
        fi = len(fmts)
        # S-015: the og stores min/max in KiB; convert ONCE here to bytes.
        min_kib = int(e.get("min", 0) or 0)
        max_kib = int(e.get("max", 0) or 0)
        # The og treats a zero/absent max as 512000 KiB (500 MiB, the
        # 0x7d000 default). Rather than shipping a silent default-rule
        # divergence, refuse to generate from a table that relies on it.
        assert max_kib > 0, f"format {ext!r} has max==0 (og default 500 MiB would apply)"
        assert 0 <= min_kib < max_kib, f"format {ext!r} min/max out of range"
        fmts.append((ext, min_kib * 1024, max_kib * 1024))
        for s in e.get("header", {}).get("signs", []):
            off, b, conf = parse_sign(s)
            hdr.append((off, b, conf, fi))
        for s in e.get("tail", {}).get("signs", []):
            off, b, conf = parse_sign(s)
            tail.append((off, b, conf, fi))

    hdr.sort(key=lambda h: (h[0], h[1][0], len(h[1])))
    tail.sort(key=lambda h: (h[0], h[1][0], len(h[1])))

    out = []
    w = out.append
    w("/* cr_rawsigns_data.cpp - GENERATED by scripts/gen_rawsigns.py from the")
    w(" * corpus raw_signs.json (the og's layer-1 carving database).")
    w(" * Do not edit by hand; regenerate after corpus updates.")
    w(" *")
    w(" * Licensed under the MIT license. See LICENSE.")
    w(" */")
    w("")
    w('#include "cr/carve/cr_rawsigns.h"')
    w("")
    w("namespace cr {")
    w("namespace carve {")
    w("namespace rawsigns {")
    w("")
    w(f"constexpr u32 kFormatCount = {len(fmts)};")
    w(f"constexpr u32 kHeaderSignCount = {len(hdr)};")
    w(f"constexpr u32 kTailSignCount = {len(tail)};")
    w("")
    w("const RawSignFormat kFormats[kFormatCount] = {")
    for ext, mn, mx in fmts:
        w(f'    {{"{ext}", {mn}ull, {mx}ull}},')
    w("};")
    w("")
    w("/* sorted by (offset, first byte, length) for the dispatch buckets */")
    w("const RawSign kHeaderSigns[kHeaderSignCount] = {")
    for off, b, conf, fi in hdr:
        hexs = ", ".join(f"0x{x:02x}" for x in b)
        w(f"    {{{off}, {len(b)}, {{{hexs}}}, {conf}, {fi}}},")
    w("};")
    w("")
    w("const RawSign kTailSigns[kTailSignCount] = {")
    for off, b, conf, fi in tail:
        hexs = ", ".join(f"0x{x:02x}" for x in b)
        w(f"    {{{off}, {len(b)}, {{{hexs}}}, {conf}, {fi}}},")
    w("};")
    w("")
    w("} // namespace rawsigns")
    w("} // namespace carve")
    w("} // namespace cr")
    open("src/core/carve/cr_rawsigns_data.cpp", "w").write("\n".join(out) + "\n")
    print(
        f"generated: {len(fmts)} formats, {len(hdr)} header signs, {len(tail)} tail signs"
    )


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""gen_filefilter.py - generate the compiled filter-category table from the
corpus FileFilter.xml (the og's runtime filter document, 8 categories /
1,481 unique extensions - M-023).

Corpus format (og-codebase/FileFilter.xml):
    <xml RootName="All types" ...>
      <FileCategory Description="Graphic" ...>
        <FileType ...>
          <Extention>.tif</Extention> ...

The og's own category order fixes cross-listed conflicts (first writer
wins): the two cross-listed extensions at corpus 03ad46c are
ari (Video then Archive) and md (Document then Archive).

Category mapping to the core enum (cr_query.h):
    Graphic -> Image, Document -> Document, Email -> Email,
    Audio -> Audio, Video -> Video, Other -> Other (0 extensions),
    Archive -> Archive, Bookmarks -> Bookmarks.

Output: src/core/query/cr_filefilter_data.cpp - one sorted array
(binary-searched by cr_query.cpp's category_for_extension) plus the
category of every extension as a lowercase no-dot string. Regenerate
after corpus updates:
    python3 scripts/gen_filefilter.py <path-to-FileFilter.xml>

Licensed under the MIT license. See LICENSE.
"""

import sys
import xml.etree.ElementTree as ET

CAT_MAP = {
    "Graphic": "Image",
    "Document": "Document",
    "Email": "Email",
    "Audio": "Audio",
    "Video": "Video",
    "Other": "Other",
    "Archive": "Archive",
    "Bookmarks": "Bookmarks",
}


def main():
    src = (
        sys.argv[1]
        if len(sys.argv) > 1
        else "../easeus-drw-research/og-codebase/FileFilter.xml"
    )
    root = ET.parse(src).getroot()

    entries = []  # (ext, category-enum)
    seen = set()
    cross_listed = []
    for cat in root.findall("FileCategory"):
        cname = cat.get("Description")
        if cname not in CAT_MAP:
            raise SystemExit(f"unknown corpus category: {cname}")
        enum = CAT_MAP[cname]
        for ft in cat.findall("FileType"):
            for e in ft.findall("Extention"):
                ext = e.text.strip().lstrip(".").lower()
                if not ext:
                    continue
                if ext in seen:
                    cross_listed.append(ext)
                    continue  # first writer wins (the og's document order)
                seen.add(ext)
                entries.append((ext, enum))

    entries.sort(key=lambda x: x[0])

    out = sys.argv[2] if len(sys.argv) > 2 else "src/core/query/cr_filefilter_data.cpp"
    with open(out, "w") as f:
        f.write(
            "/* cr_filefilter_data.cpp - GENERATED by scripts/gen_filefilter.py\n"
            " * from the corpus FileFilter.xml (og-codebase, 8 categories /\n"
            " * 1,481 unique extensions at corpus 03ad46c). DO NOT EDIT - edit the\n"
            " * generator and regenerate. Corpus citation: M-023's first-hand\n"
            " * XML parse; cross-listed extensions resolved by the og's document\n"
            " * order (first writer wins: ari/gz/insp/insv/jar/md/uzip/xz).\n"
            " *\n"
            " * Licensed under the MIT license. See LICENSE.\n"
            " */\n\n"
            '#include "cr/query/cr_query.h"\n\n'
            "namespace cr {\n"
            "namespace query {\n"
            "namespace filefilter_data {\n\n"
            "struct ExtCat {\n"
            "    const char* ext;\n"
            "    Category cat;\n"
            "};\n\n"
            "/* sorted by ext (ASCII) for binary search. extern on the\n"
            " * definitions: const namespace-scope objects default to\n"
            " * internal linkage in C++ (the extern qualifier restores it). */\n"
            "extern const ExtCat kEntries[] = {\n"
        )
        for ext, cat in entries:
            f.write(f'    {{"{ext}", Category::{cat}}},\n')
        f.write(
            "};\n\n"
            f"extern const size_t kCount = {len(entries)};\n\n"
            "} // namespace filefilter_data\n"
            "} // namespace query\n"
            "} // namespace cr\n"
        )

    print(f"wrote {out}: {len(entries)} extensions")
    if cross_listed:
        print(f"cross-listed (first writer wins): {sorted(set(cross_listed))}")


if __name__ == "__main__":
    main()

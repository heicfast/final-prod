#!/usr/bin/env python3
"""gen_dict.py - generate the compiled password-dictionary table from the
corpus Dict file (the og's BitLocker/encrypted-document unlock aid,
228 entries; config-data-reference.md :20 "Dict (2,742 B, 228 entries -
byte-verified) - password brute-force dictionary").

The corpus file's grammar (verified byte-level this session):
  - pure ASCII, CRLF line terminators
  - every line except the last is "<password>," (comma-terminated); the
    final line carries no comma and no trailing CRLF
  - 228 entries, lengths 2..20, no embedded commas

The entries are common-password list members (numeric-first then common
words - a leaked-credential-list derivative, facts rather than creative
expression); the corpus documents the file as the shipped ground truth
for this capability, the same posture as raw_signs.json (the repo's
established corpus-data conversion precedent).

The pool is emitted as NUMERIC char initializers - escape-proof by
construction (a leading digit after a NUL can never reparse as an octal
escape, which a plain string literal would risk).

Output: src/core/recovery/cr_dict_data.cpp - one byte pool + index.
Regenerate after corpus updates:
    python3 scripts/gen_dict.py <path-to-Dict>

Licensed under the MIT license. See LICENSE.
"""

import sys

MAX_PW = 32  # accepted password length cap (corpus max observed: 20)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "../easeus-drw-research/og-codebase/Dict"
    data = open(src, "rb").read()
    assert len(data) == 2742, f"unexpected corpus Dict size: {len(data)}"
    text = data.decode("ascii")
    entries = []
    for line in text.replace("\r", "").split("\n"):
        if not line:
            continue
        if line.endswith(","):
            line = line[:-1]
        assert line, "empty entry after comma strip"
        assert "," not in line, f"embedded comma: {line!r}"
        assert 1 <= len(line) <= MAX_PW, f"entry out of length cap: {line!r}"
        entries.append(line)
    assert len(entries) == 228, f"unexpected entry count: {len(entries)}"
    assert entries[0] == "12345678" and entries[-1] == "simmons", (
        f"unexpected boundary entries: {entries[0]!r}/{entries[-1]!r}")

    pool = bytearray()
    offsets = []
    for e in entries:
        offsets.append(len(pool))
        pool += e.encode("ascii") + b"\0"

    out = []
    out.append("/* cr_dict_data.cpp - GENERATED by scripts/gen_dict.py from the")
    out.append(" * corpus Dict file (the og's password-dictionary unlock aid,")
    out.append(" * config-data-reference.md :20 - 228 entries, byte-verified shape).")
    out.append(" * Do not edit by hand; regenerate after corpus updates.")
    out.append(" *")
    out.append(" * Licensed under the MIT license. See LICENSE.")
    out.append(" */")
    out.append("")
    out.append('#include "cr/recovery/cr_dict.h"')
    out.append("")
    out.append("namespace cr {")
    out.append("namespace dict {")
    out.append("")
    out.append("/* One byte pool: every entry NUL-terminated, back-to-back (the og's")
    out.append(" * file order preserved: numeric-first, then common words). Numeric")
    out.append(" * initializers keep the generated literal escape-proof. */")
    out.append(f"constexpr char kDictPool[{len(pool)}] = {{")
    for i in range(0, len(pool), 16):
        chunk = pool[i:i + 16]
        out.append("    " + " ".join(f"0x{b:02x}," for b in chunk))
    out.append("};")
    out.append("")
    out.append("const char* const kDictEntries[kDictEntryCount] = {")
    for off in offsets:
        out.append(f"    kDictPool + {off},")
    out.append("};")
    out.append("")
    out.append("} // namespace dict")
    out.append("} // namespace cr")
    out.append("")
    open("src/core/recovery/cr_dict_data.cpp", "w").write("\n".join(out))
    print(f"generated {len(entries)} entries, pool {len(pool)} bytes")


if __name__ == "__main__":
    main()
